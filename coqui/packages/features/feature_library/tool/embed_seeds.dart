// Embeds the progress seeds of coqui/ref/pantallas/seeds/ in tool/dev_seeds.dart, so the dev entry's web build
// (which cannot read files) can put each reference state's progress into the fake store.
//
//   dart run tool/embed_seeds.dart            (in this package)
//
// Only the four states of the shelf and the reader are embedded: vacio (nothing played), curso (mid-course),
// casi (all but one story of La cocina), todo (everything built so far played).
import 'dart:io';

const seeds = ['vacio', 'curso', 'casi', 'todo'];

void main() {
  final here = File.fromUri(Platform.script).parent.parent.path;
  final dir = '$here/../../../ref/pantallas/seeds';
  final out = StringBuffer()
    ..writeln(
      '// Generated by tool/embed_seeds.dart from coqui/ref/pantallas/seeds/. Do not edit.',
    )
    ..writeln()
    ..writeln(
      '/// The progress of each reference state, as the old app keeps it under `coqui.palabras.v1`.',
    )
    ..writeln('const Map<String, String> devSeeds = {');
  for (final name in seeds) {
    final text = File('$dir/$name.json').readAsStringSync().trim();
    if (text.contains("'''")) {
      stderr.writeln('$name.json holds a triple quote');
      exit(1);
    }
    out.writeln("  '$name': r'''$text''',");
  }
  out.writeln('};');
  File('$here/tool/dev_seeds.dart').writeAsStringSync(out.toString());
  stdout.writeln('wrote tool/dev_seeds.dart (${seeds.length} seeds)');
}
