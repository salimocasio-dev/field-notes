// Embeds, for the dev entry's web build, the course and the progress seeds it runs on (a dev entry cannot read
// files at run time on the web, and `coqui_testing`'s sample course is too small: the Repaso pairs of the whole
// course and the level-check items are what the reference pictures were taken with).
//
//   cd coqui/packages/features/feature_review && node tool/embed_dev_data.mjs
//
// Writes tool/dev_data.g.dart:
//   devCourseFiles   the files coqui_testing's FakeCourseCatalog reads, from historia/: datos/curso.json (with one
//                    extra "story", cual-clips, that carries the clip lines of every cual-*.json, so that the
//                    catalog can give a clip's text), datos/nivel.json, datos/fijos.json, datos/llamadas.json,
//                    cuentos/cual-*.json (byte for byte), cuentos/<story>.json reduced to its focus_words (what
//                    the level check reads), audio/marcas.json (a mark for each cual clip)
//   devSeeds         coqui/ref/pantallas/seeds/*.json, byte for byte: the progress states the reference pictures
//                    were taken in (the dev entry loads one into the fake store through `import`)
//
// Nothing in historia/ or ref/ is changed.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = path.resolve(here, '..');
const coqui = path.resolve(pkg, '..', '..', '..');
const historia = path.resolve(coqui, '..', 'historia');
const seeds = path.join(coqui, 'ref', 'pantallas', 'seeds');
const read = (p) => fs.readFileSync(path.join(historia, p), 'utf8');

const ctx = vm.createContext({});
vm.runInContext(read('curso.js') + ';this.CURSO=CURSO', ctx);
const CURSO = JSON.parse(JSON.stringify(ctx.CURSO));

const files = {};
files['datos/fijos.json'] = read('datos/fijos.json');
files['datos/llamadas.json'] = read('datos/llamadas.json');
files['datos/nivel.json'] = read('datos/nivel.json');
const clips = {};
const marcas = {};
for (const f of CURSO.cual) {
  const text = read(`cuentos/${f}.json`);
  files[`cuentos/${f}.json`] = text;
  for (const [id, c] of Object.entries(JSON.parse(text).clips)) {
    clips[id] = c;
    marcas[id] = [0, 1000, 1000];
  }
}
files['cuentos/cual-clips.json'] = JSON.stringify({ clips });
files['audio/marcas.json'] = JSON.stringify(marcas);
const cuentos = {};
for (const l of CURSO.lugares) {
  for (const id of l.cuentos || []) {
    cuentos[id] = CURSO.cuentos[id] || { t: id, min: 1 };
    let focus = [];
    try {
      focus = JSON.parse(read(`cuentos/${id}.json`)).focus_words || [];
    } catch (e) {
      // no file: the level check skips the story, as nivel.js does
      delete cuentos[id];
      continue;
    }
    files[`cuentos/${id}.json`] = JSON.stringify({ focus_words: focus, clips: {} });
  }
}
cuentos['cual-clips'] = { t: 'cual-clips', min: 1 };
files['datos/curso.json'] = JSON.stringify({
  lugares: CURSO.lugares.map((l) => ({ ...l, cuentos: (l.cuentos || []).filter((id) => cuentos[id]) })),
  cuentos,
  cual: CURSO.cual,
});

const lit = (s) => {
  if (s.includes("'''")) throw new Error("a file has ''' in it");
  return `r'''${s}'''`;
};
let dart = `// Generated by tool/embed_dev_data.mjs. Do not edit.

/// The files of the course the dev entry runs on (see tool/embed_dev_data.mjs).
const Map<String, String> devCourseFiles = {
`;
for (const [k, v] of Object.entries(files).sort(([a], [b]) => (a < b ? -1 : 1))) dart += `  '${k}': ${lit(v)},\n`;
dart += `};

/// The progress states of coqui/ref/pantallas/seeds/, by name.
const Map<String, String> devSeeds = {
`;
for (const f of fs.readdirSync(seeds).filter((f) => f.endsWith('.json')).sort()) {
  dart += `  '${f.replace(/\.json$/, '')}': ${lit(fs.readFileSync(path.join(seeds, f), 'utf8').trim())},\n`;
}
dart += '};\n';
fs.writeFileSync(path.join(pkg, 'tool', 'dev_data.g.dart'), dart);
spawnSync('dart', ['format', path.join(pkg, 'tool', 'dev_data.g.dart')], { stdio: 'ignore' });
console.log('tool/dev_data.g.dart:', Object.keys(files).length, 'files,', fs.readdirSync(seeds).length, 'seeds');
