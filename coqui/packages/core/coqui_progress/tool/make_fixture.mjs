// Makes test/fixtures/progress_fixture.dart from the recordings in coqui/ref/progress/.
//
//   node tool/make_fixture.mjs        (from coqui/packages/core/coqui_progress/; Node 22, nothing to install)
//
// Why: `dart test -p chrome` cannot read files, so the same replay as on the VM reads Dart constants.
// test/fixture_files_test.dart (VM only) checks that this file still equals the recordings; when
// coqui/ref/progress/ is made again (node coqui/tool/ref/progress/make.mjs), run this again and commit.
//
// What it writes:
//  - every sequence file of both zones as one JSON text, with each step's `store` (and
//    `initial.store`) turned into its own JSON text. The test decodes that text to compare the store as
//    numbers, and compares the text the store wrote byte for byte: it is JSON.stringify of the store, which
//    is what palabras.js saved.
//  - index.json as text.
//  - numberCases: doubles with what JSON.stringify writes for each, to test jsNumberToString.
//
// The result is formatted with `dart format`.
import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, '..');
const ref = resolve(pkg, '../../../ref/progress');
const out = resolve(pkg, 'test/fixtures/progress_fixture.dart');
const zones = ['UTC', 'America_New_York'];

// A Dart expression for a string: raw, with each ' written apart.
const dartString = (s) =>
  s
    .split("'")
    .map((p) => `r'${p}'`)
    .join(` "'" `);

const lines = [];
lines.push('// Generated by tool/make_fixture.mjs from coqui/ref/progress/. Do not edit: run the tool again.');
lines.push('');
lines.push('/// The zones the recordings were made in, as their folders are named.');
lines.push(`const fixtureZones = <String>[${zones.map((z) => `'${z}'`).join(', ')}];`);
lines.push('');
lines.push('/// ref/progress/index.json, as text.');
lines.push(`const fixtureIndex = ${dartString(JSON.stringify(JSON.parse(readFileSync(join(ref, 'index.json'), 'utf8'))))};`);
lines.push('');
lines.push('/// `zone/sequence`: the sequence file as JSON text, each `store` as a JSON text of its own.');
lines.push('const fixtureSequences = <String, String>{');
let count = 0;
for (const zone of zones) {
  for (const file of readdirSync(join(ref, zone)).filter((f) => f.endsWith('.json')).sort()) {
    const j = JSON.parse(readFileSync(join(ref, zone, file), 'utf8'));
    j.initial.store = JSON.stringify(j.initial.store);
    for (const s of j.steps) s.store = JSON.stringify(s.store);
    lines.push(`  '${zone}/${file.replace(/\.json$/, '')}': ${dartString(JSON.stringify(j))},`);
    count++;
  }
}
lines.push('};');
lines.push('');

// ---- numbers: what JSON.stringify writes -------------------------------------------------------
function mulberry32(a) {
  return () => {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rnd = mulberry32(20261119);
const numbers = [
  0, -0, 1, -1, 5, 2.5, 6.25, 15.625, 0.1, 0.5, 1 / 3, 1 / 9, 1e-6, 1.5e-6, 1e-7, 1.5e-7, 123e-9, 5e-324, 2.2250738585072014e-308,
  1.7976931348623157e308, 100, 1e20, 1e21, 1.5e21, 123456789012345680000, 2 ** 53, 2 ** 53 + 2, 2 ** 60, 2 ** 66, 2 ** 70,
  1772744400000, 1772744400000.5, 1772528400000 + 2.5 * 864e5, 1772528400000 + 6.25 * 864e5, 1772528400000 + (1 / 3) * 864e5,
  -1772528400000, -0.000001234, 1e300, 12.5, 30, 864e5, 14 * 864e5, 0.3333333333333333, 0.1 + 0.2, 4.35, 4503599627370496.5,
];
for (let n = 0; n <= 40; n++) numbers.push(1772528400000 + 2.5 ** n * 864e5, 2.5 ** n, (1 / 3) ** n);
const view = new DataView(new ArrayBuffer(8));
while (numbers.length < 420) {
  if (numbers.length % 3 === 0) {
    view.setUint32(0, Math.floor(rnd() * 4294967296));
    view.setUint32(4, Math.floor(rnd() * 4294967296));
    const x = view.getFloat64(0);
    if (Number.isFinite(x)) numbers.push(x);
  } else {
    numbers.push(Number((rnd() * 10 ** Math.floor(rnd() * 24 - 8)).toPrecision(1 + Math.floor(rnd() * 16))));
  }
}
lines.push('/// A double and what JSON.stringify writes for it (palabras.js, save).');
lines.push('const numberCases = <(double, String)>[');
for (const x of numbers) {
  const literal = Object.is(x, -0) ? '-0.0' : x.toExponential();
  lines.push(`  (${literal}, '${JSON.stringify(x)}'),`);
}
lines.push('];');
lines.push('');

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join('\n'));
execFileSync('dart', ['format', out], { stdio: 'ignore' });
console.log(`wrote ${out}: ${count} sequences, ${numbers.length} numbers`);
